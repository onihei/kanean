import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js'

/**
 * 定型手順の入口（mcp-server spec「定型手順の配布」）。
 *
 * ツールの説明文は「何ができるか」しか伝えない。**順序と前提はここで配る。**
 * スキルと違い prompts はサーバ側にあるので、利用者は Kanean 本体と
 * MCP バンドル以外に何も導入しなくてよい。
 */

/** どの手順でも最初に踏む前提。ここを外すと帳簿の取り違えや空の帳票を掴む。 */
const PREAMBLE = [
  'まず kanean_get_context を呼んで現在地（帳簿・会計年度・承認待ち件数）を確認する。',
  '帳簿が2冊以上あると選択肢が返る。その場合は推測せず、どの帳簿かを利用者に尋ねる。',
  'Kanean が起動していない場合は、起動してよいか利用者に確認してから kanean_start_app を呼ぶ。',
].join('\n')

/** どの手順でも守る境界。 */
const BOUNDARY = [
  '仕訳の確定・承認、マスタや期首残高の編集はここからはできない。必要なときは Kanean の画面へ誘導する。',
  '承認待ちの仕訳は帳票の集計に入っていない。数字を伝えるときは、その件数も併せて伝える。',
].join('\n')

function userPrompt(text: string) {
  return { messages: [{ role: 'user' as const, content: { type: 'text' as const, text } }] }
}

export function registerPrompts(server: McpServer): void {
  server.registerPrompt(
    'kanean_this_month',
    {
      title: '今月の状況',
      description: 'Kanean の今月の収支と、承認待ちの有無を確認する。',
    },
    () =>
      userPrompt(
        [
          'Kanean の今月の状況を教えてください。',
          '',
          PREAMBLE,
          '',
          '次に、今月の損益（kanean_get_profit_and_loss）と、必要なら試算表を見る。',
          '報告は「今月いくら儲かっているか」を先に1文で述べ、内訳はその後に置く。',
          '',
          BOUNDARY,
        ].join('\n'),
      ),
  )

  server.registerPrompt(
    'kanean_import',
    {
      title: '連携サービスから取り込む',
      description: '銀行・カード・EC の明細を取り込み、科目を当てて未確定の仕訳を作る。',
    },
    () =>
      userPrompt(
        [
          'Kanean に連携サービスの明細を取り込んでください。',
          '',
          PREAMBLE,
          '',
          '手順:',
          '1. kanean_list_linked_services で対象を確かめる。未登録なら先に登録の要否を利用者に尋ねる。',
          '2. kanean_start_import で開始する。**取得範囲は指定しない**',
          '   （既定が「開いている会計期間 ∩ 前回取得以降」で、指定すると差分の起点が前進せず取りこぼしが残る）。',
          '3. ブラウザ窓が開いたら、ログインと2要素認証は**利用者が行う**。',
          '   認証情報を尋ねてはならないし、代わりに入力してもいけない。',
          '4. kanean_get_import_status で進行を追う。完了したら件数の内訳（受理・重複・期間外・未確定）を伝える。',
          '   **取込は分類を待たない。** 科目が決まらなかった明細は未確定の draft として帳簿に並んでいる。',
          '5. kanean_list_unclassified で未確定の品名・摘要を取り、科目を当てて kanean_classify_drafts で返す。',
          '   一緒に返る policy（この帳簿の分類方針）と history（過去の確定実績）に従う。',
          '   金額・取引識別子・残高は渡されない。**文字と方針と履歴だけで判断する。**',
          '   **reason（理由1行）と confidence を必ず添える。** 利用者は確信度 high をまとめて確定し、',
          '   それ以外を1件ずつ見る。根拠が無いと全件を手で開くことになる。',
          '   判断がつかないものは無理に埋めず、answers から外して未確定のまま残す（推測で科目を作らない）。',
          '',
          '失敗したときは kanean_get_import_diagnostic を見る。',
          'calibratable が true のときだけ kanean_update_site_calibration で較正を直して取り直す。',
          'false のときは較正の更新を繰り返さず、画面の状態を利用者に確認してもらう。',
          '',
          BOUNDARY,
          '取り込んだ仕訳はすべて未確定（draft）。確定は利用者が Kanean の画面で行う。',
        ].join('\n'),
      ),
  )

  server.registerPrompt(
    'kanean_receipts',
    {
      title: 'レシートの取込',
      description:
        'スマホで撮ったレシートの inbox を処理し、現金は起票・カードは突合して証憑を残す。' +
        '登録できたものだけ中継コピーを消す。',
    },
    () =>
      userPrompt(
        [
          'スマホから届いたレシートを Kanean に取り込んでください。',
          '',
          PREAMBLE,
          '',
          '手順:',
          '1. inbox（iCloud Drive の Kanean フォルダ）を見る。1件は同じ ULID を共有する',
          '   **画像とメタ JSON の対**で表される。**対が揃っていない件は触らない**',
          '   （同期の途中なので、次の機会に持ち越す）。',
          '2. メタの paymentMethod で経路が割れる。**ここを取り違えると二重計上になる。**',
          '   - cash → kanean_import_cash_receipt で起票する（draft 仕訳＋証憑添付）。',
          '   - card → kanean_match_card_receipt で候補を出す。**起票してはならない**',
          '     （カードの明細は連携サービスの取込が持つ）。候補は自動で選ばず利用者に選んでもらう。',
          '3. 画像から読み取った日付・金額・店名を渡す。メタの ocr は端末の下読みなので、',
          '   **画像を見た結果を優先する**。読み取れないものは推測で埋めず、省いて渡す',
          '   （起票されずに理由が返る）。メタの usage・partySize・participants・memo は',
          '   そのまま渡す（交際費／会議費の判断材料であり、撮影時にしか取れない）。',
          '4. **中継コピーを消してよいのは、登録と証憑保存の両方が完了した件だけ**。',
          '   重複として弾かれた件も既に証憑があるので消してよい。',
          '   それ以外（読み取り不能・期間外・カードの未突合・失敗）は**画像を残す**。',
          '   順序を逆にすると、証憑が本体に無いまま画像だけが消える。',
          '5. 処理した件ごとに status を書き戻す（登録できたかどうかと、できなかった理由）。',
          '   端末はこれを見て「登録済み」を表示する。書き戻さないと送信済みのまま止まる。',
          '',
          '最後に、登録・重複・未登録の件数と、未登録の理由を利用者に伝える。',
          '',
          BOUNDARY,
          '取り込んだ仕訳はすべて未確定（draft）。確定は利用者が Kanean の画面で行う。',
        ].join('\n'),
      ),
  )

  server.registerPrompt(
    'kanean_filing',
    {
      title: '確定申告の転記',
      description:
        '国税庁の確定申告書等作成コーナーへ、Kanean の入力指示書どおりに転記して e-Tax 送信を支援する。' +
        '認証と送信は利用者が行う。',
    },
    () =>
      userPrompt(
        [
          'Kanean の申告データを、国税庁の確定申告書等作成コーナーへ転記してください。',
          '',
          PREAMBLE,
          '',
          '手順:',
          '1. kanean_get_filing_precheck で前提を点検する。不備（blocking）があれば転記に進まず、',
          '   解消方法と該当画面を利用者に示す。注意（warning）は伝えたうえで進んでよい。',
          '2. kanean_get_filing_sheet で入力指示書を取得する。以後、**入力する数値・選択はすべて',
          '   指示書のみを源とする**。計算・推測・補完で値を作らない。指示書に無い入力を画面が',
          '   求めたら、埋めずに利用者に確認する。',
          '3. ブラウザで作成コーナーを開き、指示書の画面グループ順（A 決算書 → B 所得税 → C 消費税）に',
          '   転記する。**ログイン・マイナンバーカードの認証（QR コードのスマホ読み取り）は利用者が行う**。',
          '   認証情報や暗証番号を尋ねてはならないし、代わりに入力してもいけない。',
          '   認証画面に着いたら利用者に声をかけ、完了を待ってから続ける。',
          '4. kind=verify の欄は入力しない。コーナーの自動計算値が指示書と一致することを確認する。',
          '   **一致しないときはその場で止まり**、欄名と両方の値を利用者に報告する（続行しない）。',
          '5. 画面グループの区切りごとに、コーナーの途中保存（.data ファイルのダウンロード）を利用者に',
          '   案内する。セッションが切れたら保存ファイルから再開する。',
          '6. 最終の計算結果画面で、表示された税額と指示書の checksum を1円単位で突き合わせ、',
          '   結果を利用者に提示する。**一致した場合のみ**送信操作（利用者が行う）へ案内する。',
          '   不一致なら送信に進まず、完了記録も作らない。',
          '7. 送信後、受信通知と申告書控えの PDF をダウンロードしてもらい、kanean_record_filing で',
          '   受付番号・提出日とともに記録する（控えのファイルパスを attachmentPaths に渡す）。',
          '',
          'システムも AI も「提出可能」を宣言しない。数字の最終確認は利用者と税理士に委ねる。',
          '',
          BOUNDARY,
        ].join('\n'),
      ),
  )

  server.registerPrompt(
    'kanean_closing_check',
    {
      title: '決算前チェック',
      description: '決算前に、数字が整っているか・人の判断待ちが残っていないかを点検する。',
    },
    () =>
      userPrompt(
        [
          'Kanean の決算前チェックをしてください。',
          '',
          PREAMBLE,
          '',
          '点検する観点:',
          '- 承認待ちの仕訳が残っていないか（残っていれば件数と、確認先の画面を示す）',
          '- 試算表の貸借が一致しているか（kanean_get_trial_balance の balanced）',
          '- 未確定勘定など、判断が保留されている科目に残高が無いか',
          '- 納税予測（kanean_get_tax_forecast）の見込み額',
          '',
          '見つかった問題は、深刻な順に並べて、それぞれ何をすれば解消するかを添える。',
          '問題が無ければ、無いと明言する（無理に指摘を作らない）。',
          '',
          BOUNDARY,
          '納税予測は決算整理前の見込みであり、提出できる申告額ではないことを必ず添える。',
        ].join('\n'),
      ),
  )
}
